#!/usr/bin/env python3
"""Run a parliament over open PR diffs and collect the Split for judging.

The question this answers is NOT "did the models get the right answer".
It is: **does the Split tell me something I did not already know?**

That is the load-bearing assumption behind agent-facing use — if the
disagreement signal is mush, nothing built on top of it works. Twenty
debates and honest notes settle it faster than any amount of planning.

Usage (from a checkout, with Ollama running locally):

    python scripts/experiment_pr_debate.py --prs 26,27,33
    python scripts/experiment_pr_debate.py --prs 26 --mock      # plumbing check

Costs nothing: local models via Ollama. Expect a few minutes per PR --
seven model calls per debate, and local inference is not fast.

Results land in ./pr-debate-runs/ as one JSON per PR plus NOTES.md, which
is the actual deliverable. Fill in the verdict lines by hand.
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
import textwrap
from datetime import datetime, timezone
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUT = REPO_ROOT / "pr-debate-runs"

# Local models have small context windows; a big diff silently degrades the
# debate into "the models did not really read it". Truncate loudly instead.
DEFAULT_MAX_DIFF_CHARS = 6000

OLLAMA_CONFIG = """\
# Generated by scripts/experiment_pr_debate.py
# Three DIFFERENT local models -- the point is decorrelated opinions.
# Same model three times just produces three copies of one opinion.
parliament:
  name: PR Review Parliament
  members:
    - name: Llama
      provider: ollama
      model: llama3.1
    - name: Qwen
      provider: ollama
      model: qwen2.5-coder
    - name: Mistral
      provider: ollama
      model: mistral
providers:
  ollama:
    base_url: http://localhost:11434/v1
display:
  show_debate: false
hansard:
  level: archive
"""

QUESTION_TEMPLATE = """\
Review this pull request diff and decide: is it safe to merge as-is?

Consider correctness, edge cases, and anything the change breaks that is not
visible in the diff itself. If you would block the merge, say exactly what
would have to change.

--- PR #{number}: {title} ---

{diff}
"""


def run(cmd: list[str], **kw) -> subprocess.CompletedProcess:
    return subprocess.run(cmd, cwd=REPO_ROOT, capture_output=True, text=True, **kw)


def fetch_pr_diff(number: int, base: str, max_chars: int) -> tuple[str, bool]:
    """Return (diff_text, was_truncated) for a PR, fetching its head first."""
    ref = f"pr-experiment-{number}"
    fetch = run(["git", "fetch", "-q", "origin", f"pull/{number}/head:{ref}", "--force"])
    if fetch.returncode != 0:
        raise RuntimeError(f"could not fetch PR #{number}: {fetch.stderr.strip()}")

    merge_base = run(["git", "merge-base", base, ref])
    if merge_base.returncode != 0:
        raise RuntimeError(f"no merge base for PR #{number} against {base}")

    diff = run(["git", "diff", merge_base.stdout.strip(), ref])
    if diff.returncode != 0:
        raise RuntimeError(f"could not diff PR #{number}")

    text = diff.stdout
    truncated = len(text) > max_chars
    if truncated:
        text = text[:max_chars] + "\n\n[... diff truncated for context limits ...]"
    return text, truncated


def pr_title(number: int) -> str:
    """Best-effort title from the PR's newest commit; the API is not needed."""
    ref = f"pr-experiment-{number}"
    out = run(["git", "log", "-1", "--format=%s", ref])
    return out.stdout.strip() if out.returncode == 0 else f"PR #{number}"


def debate(question: str, config: Path | None, mock: bool) -> dict:
    cmd = [sys.executable, "-m", "parliament.cli", "ask", "--json", "--no-show-debate"]
    if mock:
        cmd.append("--mock")
    elif config is not None:
        cmd += ["--config", str(config)]
    cmd.append(question)

    proc = run(cmd)
    if proc.returncode != 0:
        raise RuntimeError(f"parliament failed:\n{proc.stderr.strip()[:2000]}")
    # Diagnostics go to stderr (PR #18), so stdout is clean JSON.
    return json.loads(proc.stdout)


def summarise(hansard: dict) -> dict[str, str]:
    s = hansard.get("synthesis") or {}
    return {
        "consensus": (s.get("consensus") or "").strip(),
        "split": (s.get("split") or "").strip(),
        "risks": (s.get("risks") or "").strip(),
        "recommendation": (s.get("recommendation") or "").strip(),
    }


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--prs", default="26,27,33", help="comma-separated PR numbers")
    ap.add_argument("--base", default="origin/main", help="base ref to diff against")
    ap.add_argument("--config", type=Path, default=None, help="parliament config (default: generated Ollama one)")
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT, help="output directory")
    ap.add_argument("--max-diff-chars", type=int, default=DEFAULT_MAX_DIFF_CHARS)
    ap.add_argument("--mock", action="store_true", help="mock providers — checks plumbing, tells you nothing")
    args = ap.parse_args()

    numbers = [int(n) for n in args.prs.split(",") if n.strip()]
    args.out.mkdir(parents=True, exist_ok=True)

    config = args.config
    if config is None and not args.mock:
        config = args.out / "ollama-parliament.yaml"
        if not config.exists():
            config.write_text(OLLAMA_CONFIG, encoding="utf-8")
            print(f"wrote {config}")
            print("  Edit the three model names to match `ollama list` before a real run.\n")

    run(["git", "fetch", "-q", "origin", args.base.split("/")[-1]])

    results = []
    for number in numbers:
        print(f"── PR #{number} " + "─" * 40)
        try:
            diff, truncated = fetch_pr_diff(number, args.base, args.max_diff_chars)
            title = pr_title(number)
            if truncated:
                print(f"  diff truncated to {args.max_diff_chars} chars")
            print(f"  {title}")
            print("  debating (this takes a few minutes on local models)...")

            hansard = debate(
                QUESTION_TEMPLATE.format(number=number, title=title, diff=diff),
                config,
                args.mock,
            )
        except Exception as e:  # noqa: BLE001 - experiment script, keep going
            print(f"  FAILED: {e}\n")
            results.append({"pr": number, "error": str(e)})
            continue

        path = args.out / f"pr-{number}.json"
        path.write_text(json.dumps(hansard, indent=2), encoding="utf-8")

        parts = summarise(hansard)
        results.append({"pr": number, "title": title, **parts})

        print("\n  SPLIT (the thing you are judging):")
        print(textwrap.indent(textwrap.fill(parts["split"] or "(empty)", 76), "    "))
        print(f"\n  → {path}\n")

    notes = args.out / "NOTES.md"
    lines = [
        "# PR debate experiment",
        "",
        f"Run {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')}"
        + (" — MOCK, judge nothing from this" if args.mock else ""),
        "",
        "For each PR, answer honestly. The only question that matters:",
        "**did the Split tell me something I did not already know?**",
        "",
        "Scoring: `yes` / `partly` / `no` — and one line saying why.",
        "",
    ]
    for r in results:
        lines.append(f"## PR #{r['pr']} — {r.get('title', r.get('error', ''))}")
        lines.append("")
        if "error" in r:
            lines.append(f"Failed: {r['error']}")
            lines.append("")
            continue
        lines.append("**Split as reported:**")
        lines.append("")
        lines.append("> " + (r["split"] or "(empty)").replace("\n", "\n> "))
        lines.append("")
        lines.append("- Told me something new? **TODO: yes / partly / no**")
        lines.append("- Why: TODO")
        lines.append("")
    lines += [
        "---",
        "",
        "## Verdict after all runs",
        "",
        "- How many were `yes`? TODO",
        "- Was an empty Split a sign of real agreement, or of models not engaging? TODO",
        "- Would I want this to run automatically on a risky PR? TODO",
        "",
        "If most are `no`, the agent-facing direction rests on a signal that is not there,",
        "and that is worth knowing before building an MCP server on top of it.",
    ]
    notes.write_text("\n".join(lines) + "\n", encoding="utf-8")

    print(f"Notes template: {notes}")
    print("Fill in the TODO lines — those notes are the actual result.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
